#!/usr/bin/env bash
#
# mayhem/test.sh — check the parser against upstream's OWN functional suite (hevcparser_test:
# hevcparser/tests/Parsing.cpp, 15 Boost test cases of 1777 known-answer assertions on syntax
# elements decoded from real HEVC streams) and decide every verdict here, in this script.
#
# Earlier versions ran upstream's Boost binary and scored the JUnit file it wrote. Any code linked
# into that binary (the parser sources a patch may edit, or the tree's test sources) could write a
# passing report and _exit(0), and an aborted run still counted as 14/15 (#1787, #878). Now:
#
#  1. Pinned suite, without its answers. mayhem/build.sh compiles mayhem/oracle/observe.cpp, never
#     the tree's hevcparser/tests/ (a patch can edit those, #1460). observe.cpp is upstream's
#     Parsing.cpp with the EXPECTED half of every assertion removed (generated by
#     mayhem/oracle/make-observe.py; same line numbers): each BOOST_CHECK_EQUAL(x, want) became
#     KAT_OBS(x), each BOOST_CHECK_EQUAL_COLLECTIONS kept only its parser-side range, and the local
#     arrays of expected values are gone. Each observation prints one record with the value of x,
#       "@@ <nonce> <case> <seq> <line> <value>"
#     and the runner prints "@@ <nonce> <case> END" after the case returns. No program built from the
#     tree contains an answer, and nothing a runner prints, writes or returns means "passed". So a
#     patch that redefines the macros from a tree header ("Hevc.h" is included after kat.h; an
#     earlier version compiled the expected half in, and a header that turned every check into
#     check(b, b) passed with the parser gutted) has no right value to print.
#  2. Verdicts come from this script. The answers are in mayhem/oracle/expected.txt, which is
#     checked against the SHA-256 list below and read into memory before any runner starts, and is
#     never copied to where a runner runs. A record must appear exactly once and equal its
#     expected.txt line; a missing, repeated or different record fails that assertion. <nonce> is
#     a new random number for each process (it marks the record lines; the program can read it, so
#     it is not what stops forging: a patch has no right answer to put in a record without parsing
#     the stream correctly). The HEVC streams are SHA-checked copies of mayhem/test-samples/,
#     checked again before every run.
#  3. One process per test case and build, so a crash or abort fails only that case.
#  4. Each assertion runs in two builds and must give the right answer in both (#1460):
#       N: build-tests/hevc_kat, the parser built with the project's normal flags (upstream CMake
#          Release: -O3 -DNDEBUG -fPIC);
#       G: build-fuzz/hevc_kat, linked with the GRADED objects (build-fuzz/libhevcparser.a, the
#          same objects as /mayhem/hevcesbrowser-console), so code disabled only in the fuzz build
#          (sanitizer, optimisation or macro checks) fails here;
#       W: for SINTEL_FIRST_30 only, build-fuzz/hevc_kat_twin: the parser compiled with the graded
#          flags plus -fsanitize-recover=undefined (UBSan prints its report and carries on; nothing
#          else differs, no runtime options). That stream reaches a real signed overflow in
#          BitstreamReader::getGolombU (hevcparser/src/BitstreamReader.cpp:149) that stops the
#          graded build before its first assertion.
#     The sanitized runners link mayhem/oracle/lsan_off.cc (SPEC.md §6.2 item 15): the pinned suite
#     never frees its input buffers, so leak detection is off in them only; ASan and UBSan stay on.
#
# Limits: the answers are not secret from whoever writes a patch: upstream's Parsing.cpp is in the
# tree (hevcparser/tests/) and expected.txt is in mayhem/oracle/. A patch that carries these
# streams' answers, or pulls them in from one of those files (at run time, or at compile time, e.g.
# a tree header that #includes Parsing.cpp to rebuild the table), and prints them, is not caught.
# Such a patch has to be written for these 1777 values; what is closed is every way to pass
# WITHOUT the answers (macro hijacks, forged reports or END lines, exit codes, aborts).
#
# Tests: one per assertion (1777). It passes when its N record and its G (or W) record are right
# and both processes exited 0 and printed their END line exactly once (30 processes: 15 N, 14 G,
# 1 W). A process that crashes or exits non-zero fails every assertion of its case, including the
# ones it printed before it stopped.
set -uo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH
cd "$SRC" || exit 1

emit_ctrf() {
  local tool="$1" passed="$2" failed="$3" skipped="${4:-0}" pending="${5:-0}" other="${6:-0}"
  local tests=$(( passed + failed + skipped + pending + other ))
  cat > "${CTRF_REPORT:-$SRC/ctrf-report.json}" <<JSON
{
  "results": {
    "tool": { "name": "$tool" },
    "summary": {
      "tests": $tests,
      "passed": $passed,
      "failed": $failed,
      "pending": $pending,
      "skipped": $skipped,
      "other": $other
    }
  }
}
JSON
  printf 'CTRF {"results":{"tool":{"name":"%s"},"summary":{"tests":%d,"passed":%d,"failed":%d,"pending":%d,"skipped":%d,"other":%d}}}\n' \
    "$tool" "$tests" "$passed" "$failed" "$pending" "$skipped" "$other"
  [ "$failed" -eq 0 ]
}

