fail_all() {   # fail_all <reason> : nothing could be checked
  echo "FATAL: $1" >&2
  emit_ctrf "$TOOL" 0 "$N_ASSERT"
  exit 1
}

for b in "$N_BIN" "$G_BIN" "$W_BIN"; do
  [ -x "$b" ] || fail_all "$b missing (mayhem/build.sh must build it)"
done

WORK="$(mktemp -d "${TMPDIR:-/tmp}/hevc-test.XXXXXX")" || fail_all "mktemp failed"
trap 'rm -rf "$WORK"' EXIT

check_sums() {   # check_sums <dir> <sha256 list> : every file in the list is in <dir> and matches
  ( cd "$1" && printf '%s\n' "$2" | awk 'NF == 2' | sha256sum --check --strict --quiet - ) >&2
}
list_files() { printf '%s\n' "$1" | awk 'NF == 2 { print $2 }'; }

# Private copies, checked after copying, so the checked bytes are the ones used.
PIN="$WORK/pinned"
mkdir "$PIN"
for f in $(list_files "$PINNED_SHA256"); do
  mkdir -p "$PIN/$(dirname "$f")" && cp "$SRC/mayhem/$f" "$PIN/$f" || fail_all "mayhem/$f missing"
done
check_sums "$PIN" "$PINNED_SHA256" || fail_all "mayhem/oracle/ does not match the SHA-256 list in mayhem/test.sh"
FEED="$WORK/samples"
mkdir "$FEED"
for f in $(list_files "$SAMPLES_SHA256"); do
  cp "$SRC/mayhem/test-samples/$f" "$FEED/$f" || fail_all "mayhem/test-samples/$f missing"
done
check_sums "$FEED" "$SAMPLES_SHA256" || fail_all "mayhem/test-samples/ does not match the SHA-256 list in mayhem/test.sh"

# The answers, read into memory before any runner starts; the copy is removed.
EXPECTED="$(awk '$1 == "T"' "$PIN/oracle/expected.txt")"
rm -rf "$PIN"
n="$(printf '%s\n' "$EXPECTED" | awk 'NF == 5' | wc -l)"
[ "$n" -eq "$N_ASSERT" ] || fail_all "expected.txt has $n assertions, want $N_ASSERT"

nonce() { od -An -N8 -tu8 /dev/urandom | tr -d ' \n'; }

# run_case <tier> <binary> <case> : one process runs one case in a fresh directory whose samples/
# holds the checked streams. Writes $WORK/<tier>.<case>.rec ("<tier> <case> <seq> <line> <value>"
# per record with this run's nonce), .out/.err (all output) and .ok (the run passed).
run_case() {
  local t="$1" bin="$2" c="$3" d="$WORK/run.$1.$3" n rc ends
  n="$(nonce)"; : > "$WORK/$t.$c.rec"
  check_sums "$FEED" "$SAMPLES_SHA256" || { echo ">>> $c ($t): a sample stream changed before the run" >&2; return; }
  mkdir -p "$d/samples" && cp "$FEED"/* "$d/samples/"
  ( cd "$d" && "$bin" "$n" "$d" "$c" ) > "$WORK/$t.$c.out" 2> "$WORK/$t.$c.err" < /dev/null; rc=$?
  rm -rf "$d"
  grep -a "^@@ $n $c [0-9]" "$WORK/$t.$c.out" | awk -v T="$t" '{ $1 = T; $2 = ""; print }' \
    | awk '{ $1 = $1; print }' > "$WORK/$t.$c.rec"
  ends="$(grep -acx "@@ $n $c END" "$WORK/$t.$c.out")"
  if [ "$rc" -eq 0 ] && [ "$ends" -eq 1 ]; then : > "$WORK/$t.$c.ok"
  else
    echo ">>> $c ($t, $bin): exit $rc, $ends END lines" >&2
    grep -a -m2 -E 'runtime error|ERROR: AddressSanitizer|^unknown case' "$WORK/$t.$c.err" >&2
  fi
}

runs=()
for c in $CASES; do
  run_case N "$N_BIN" "$c"; runs+=("N.$c")
  case " $W_CASES " in
    *" $c "*) run_case W "$W_BIN" "$c"; runs+=("W.$c") ;;
    *)        run_case G "$G_BIN" "$c"; runs+=("G.$c") ;;
  esac
done
[ "${#runs[@]}" -eq "$RUNS" ] || fail_all "ran ${#runs[@]} processes, want $RUNS"

# A run that did not exit 0 with exactly one END line fails every assertion of its case.
r_pass=0; r_fail=0
for r in "${runs[@]}"; do
  if [ -e "$WORK/$r.ok" ]; then r_pass=$(( r_pass + 1 )); else r_fail=$(( r_fail + 1 )); echo "${r%%.*} ${r#*.}"; fi
done > "$WORK/failed.runs"

# "T <case> <seq> <line> <value>": the N record and the G (or W) record must each appear once,
# equal "<line> <value>", and come from runs that passed.
recs=()
for r in "${runs[@]}"; do recs+=("$WORK/$r.rec"); done
read -r a_pass a_fail < <(printf '%s\n' "$EXPECTED" | awk -v WC=" $W_CASES " '
  function check(t, c, q,   k) {
    k = t SUBSEP c SUBSEP q
    if (!(k in cnt)) return t ": no record"
    if (cnt[k] > 1) return t ": " cnt[k] " records"
    if (rec[k] != $4 " " $5) return t ": got \"" rec[k] "\", want \"" $4 " " $5 "\""
    if ((t SUBSEP c) in badrun) return t ": the run failed"
    return ""
  }
  FILENAME ~ /\/failed\.runs$/ { badrun[$1 SUBSEP $2] = 1; next }
  FILENAME != "-" {
    k = $1 SUBSEP $2 SUBSEP $3; cnt[k]++
    rec[k] = (NF == 5) ? $4 " " $5 : "malformed: " $0
    next
  }
  NF == 5 && $1 == "T" {
    t2 = index(WC, " " $2 " ") ? "W" : "G"
    why = check("N", $2, $3)
    if (why == "") why = check(t2, $2, $3)
    if (why == "") pass++
    else { fail++; if (shown++ < 40) printf "FAIL %s #%d (Parsing.cpp:%d) %s\n", $2, $3, $4, why > "/dev/stderr" }
  }
  END { print pass + 0, fail + 0 }' "$WORK/failed.runs" "${recs[@]}" -)

echo "assertions: ${a_pass:-0} passed, ${a_fail:-0} failed (of $N_ASSERT); runs: $r_pass passed, $r_fail failed (of $RUNS)"

passed=${a_pass:-0}
failed=$(( N_ASSERT - passed ))
emit_ctrf "$TOOL" "$passed" "$failed"
